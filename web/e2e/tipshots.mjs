// Screenshots of the tooltips and the expanded Students tab. node e2e/tipshots.mjs <baseUrl> <outDir>
import { chromium } from 'playwright'
const base = process.argv[2] ?? 'http://localhost:5173/'
const out = process.argv[3] ?? 'e2e/shots'
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const page = await (await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'dark' })).newPage()
await page.goto(base, { waitUntil: 'networkidle' })
await page.waitForTimeout(1800)
await page.keyboard.press('Control+k')
await page.keyboard.type('elementary')
await page.locator('#search-results li button', { hasText: 'Public school' }).first().click()
const aside = page.locator('aside[aria-label="School details"]')
await aside.waitFor()
await page.waitForTimeout(2500)
await aside.getByRole('tab', { name: 'Programs', exact: true }).click()
await page.waitForTimeout(1200)
const cell = aside.locator('table[aria-label] td:not(.nowv):not(.gap)').nth(9)
const b = await cell.boundingBox()
await page.mouse.move(b.x - 5, b.y)
await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 4 })
await page.waitForTimeout(300)
await page.screenshot({ path: `${out}/tip-strip.png`, clip: { x: 960, y: 300, width: 480, height: 330 } })
await aside.getByRole('tab', { name: 'Students', exact: true }).click()
await page.waitForTimeout(1200)
const seg = aside.locator('.gb .bar i').nth(4)
await seg.scrollIntoViewIfNeeded()
const s = await seg.boundingBox()
await page.mouse.move(s.x - 4, s.y)
await page.mouse.move(s.x + s.width / 2, s.y + s.height / 2, { steps: 4 })
await page.waitForTimeout(300)
await page.screenshot({ path: `${out}/tip-gradebar.png` })
await page.mouse.move(5, 5)
await page.getByRole('button', { name: 'Expand panel' }).click()
await page.waitForTimeout(800)
await aside.locator('.body').evaluate((e) => (e.scrollTop = 0))
await page.screenshot({ path: `${out}/students-expanded.png` })
await aside.locator('.body').evaluate((e) => (e.scrollTop = e.scrollHeight))
await page.waitForTimeout(300)
await page.screenshot({ path: `${out}/students-expanded-2.png` })
await browser.close()
